-- 테이블 목록:
--   - employees : 직원 기본 정보
--   - leaves    : 연차 신청 및 승인 현황
--   - sales     : 매출 실적 (분기별)
-- =============================================================


-- =============================================================
-- 1. employees 테이블: 직원 기본 정보
-- =============================================================

CREATE TABLE IF NOT EXISTS employees (
    id                SERIAL PRIMARY KEY,
    name              VARCHAR(100) NOT NULL,           -- 직원 이름
    department        VARCHAR(100),                    -- 소속 부서
    annual_leave_days INTEGER DEFAULT 15,              -- 연간 부여 연차 일수
    used_leave_days   INTEGER DEFAULT 0               -- 사용한 연차 일수
);

COMMENT ON TABLE employees IS '직원 기본 정보 테이블';
COMMENT ON COLUMN employees.annual_leave_days IS '연간 부여 연차 일수 (기본값 15일)';
COMMENT ON COLUMN employees.used_leave_days   IS '사용한 연차 일수 (잔여 = annual - used)';


-- =============================================================
-- 2. leaves 테이블: 연차 신청 및 승인 현황
-- =============================================================

CREATE TABLE IF NOT EXISTS leaves (
    id          SERIAL PRIMARY KEY,
    employee_id INTEGER     REFERENCES employees(id),  -- 직원 외래키
    start_date  DATE,                                  -- 연차 시작일
    end_date    DATE,                                  -- 연차 종료일
    reason      TEXT,                                  -- 신청 사유
    status      VARCHAR(20) DEFAULT 'pending'          -- pending / approved / rejected
);

COMMENT ON TABLE leaves IS '연차 신청 및 승인 현황 테이블';
COMMENT ON COLUMN leaves.status IS 'pending: 대기, approved: 승인, rejected: 반려';


-- =============================================================
-- 3. sales 테이블: 매출 실적 (분기별)
-- =============================================================

CREATE TABLE IF NOT EXISTS sales (
    id          SERIAL PRIMARY KEY,
    employee_id INTEGER        REFERENCES employees(id),  -- 직원 외래키
    department  VARCHAR(100),                              -- 부서명 (조회 편의용 비정규화 컬럼)
    amount      DECIMAL(12, 2),                            -- 매출 금액 (원)
    sale_date   DATE,                                      -- 매출 발생일
    quarter     VARCHAR(10)                               -- 분기 (예: '2024-Q1')
);

COMMENT ON TABLE sales IS '매출 실적 테이블 (분기별 집계 가능)';
COMMENT ON COLUMN sales.quarter IS '분기 형식: YYYY-QN (예: 2024-Q1)';


